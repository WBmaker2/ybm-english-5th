export const lessons = grades.flatMap((grade) => grade.lessons);

export function getGradeById(gradeId) {
  return grades.find((grade) => grade.id === gradeId) || null;
}

export function getLessonsByGradeId(gradeId) {
  return getGradeById(gradeId)?.lessons || [];
}

export function getLessonById(lessonId) {
  return lessons.find((lesson) => lesson.id === lessonId) || null;
}
